"""Labelled task data built from internal text (PRD section 7.7).

Task data comes from internal documents, tickets and resolved questions. It is
never generated by a third-party model. Rules are the labelling baseline the
learned model has to beat (PRD section 12).
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass, field
from typing import Any

from llmforge.data.records import Record


@dataclass(frozen=True, slots=True)
class LabelRule:
    label: str
    keywords: tuple[str, ...]
    priority: int = 0
    scope: str = "subject"


@dataclass(slots=True)
class LabelSet:
    name: str
    rules: tuple[LabelRule, ...]
    fallback_label: str = "other"
    labels: tuple[str, ...] = field(default_factory=tuple)
    subject_chars: int = 120

    def label_for(self, text: str) -> str:
        lowered = text.lower()
        subject = lowered[: self.subject_chars]
        matches: list[tuple[int, str]] = []
        for rule in self.rules:
            haystack = subject if rule.scope == "subject" else lowered
            if any(keyword in haystack for keyword in rule.keywords):
                matches.append((rule.priority, rule.label))
        if not matches:
            return self.fallback_label
        matches.sort(key=lambda item: (-item[0], item[1]))
        return matches[0][1]

    def apply(self, records: list[Record]) -> list[dict[str, Any]]:
        labelled: list[dict[str, Any]] = []
        for record in records:
            labelled.append(
                {
                    "record_key": record.record_key,
                    "text": record.text,
                    "label": self.label_for(record.text),
                    "source_id": record.source_id,
                }
            )
        return labelled


BILLING_LABEL_SET = LabelSet(
    name="routing",
    rules=(
        LabelRule(
            "billing",
            ("invoice reconciliation", "payment retry", "payment retries", "license renewal"),
            priority=20,
        ),
        LabelRule(
            "fulfilment",
            ("shipment tracking", "returns processing", "backorderqueue", "warehouse audit"),
            priority=20,
        ),
        LabelRule(
            "onboarding",
            ("customer onboarding", "tenantquotas", "fulfilmenthub"),
            priority=10,
        ),
    ),
    fallback_label="general",
    labels=("billing", "fulfilment", "onboarding", "general"),
)


def label_counts(labelled: list[dict[str, Any]]) -> dict[str, int]:
    counts: dict[str, int] = {}
    for item in labelled:
        counts[item["label"]] = counts.get(item["label"], 0) + 1
    return dict(sorted(counts.items()))


def build_labeled_dataset(
    records: list[Record],
    label_set: LabelSet = BILLING_LABEL_SET,
) -> list[dict[str, Any]]:
    return label_set.apply(records)


Labeler = Callable[[str], str]
